<h2>1. Quem somos</h2>
<p>O Out App é uma plataforma digital de gestão, automação e organização de negócios, operada pelo Grupo Liberdade Financeira Online (CNPJ 21.233.977/0001-29). Atuamos como <strong>controlador</strong> dos dados de cadastro dos usuários e como <strong>operador</strong> dos dados que você insere na plataforma sobre seus próprios clientes.</p>

<h2>2. Dados que coletamos</h2>
<ul>
<li><strong>Dados de cadastro:</strong> nome, e-mail, telefone e senha (armazenada de forma criptografada).</li>
<li><strong>Dados de pagamento:</strong> processados por parceiros (Mercado Pago). Não armazenamos números completos de cartão.</li>
<li><strong>Dados de uso:</strong> páginas acessadas, recursos utilizados, data e hora de acesso, endereço IP e dispositivo.</li>
<li><strong>Conteúdo criado por você:</strong> cadastros, contatos, catálogos, portfólios, páginas, contratos, conversas e arquivos enviados.</li>
<li><strong>Cookies e tecnologias similares:</strong> conforme descrito na seção 7.</li>
</ul>

<h2>3. Como usamos seus dados</h2>
<ul>
<li>Criar e manter sua conta e autenticar seu acesso.</li>
<li>Fornecer, operar e melhorar os recursos da plataforma.</li>
<li>Processar pagamentos, assinaturas e emitir comprovantes.</li>
<li>Enviar comunicações operacionais (verificação de e-mail, avisos, suporte).</li>
<li>Prevenir fraudes, abusos e garantir a segurança do serviço.</li>
<li>Cumprir obrigações legais e regulatórias.</li>
</ul>

<h2>4. Bases legais (LGPD)</h2>
<p>Tratamos dados pessoais com fundamento em: execução de contrato, cumprimento de obrigação legal, legítimo interesse (segurança e melhoria do serviço) e consentimento, quando aplicável.</p>

<h2>5. Compartilhamento de dados</h2>
<p>Não vendemos seus dados. Compartilhamos apenas o necessário com prestadores que viabilizam o serviço:</p>
<ul>
<li><strong>Supabase</strong> – banco de dados, autenticação e armazenamento de arquivos.</li>
<li><strong>Mercado Pago</strong> – processamento de pagamentos.</li>
<li><strong>Resend</strong> – envio de e-mails transacionais.</li>
<li>Autoridades públicas, quando exigido por lei ou ordem judicial.</li>
</ul>

<h2>6. Armazenamento e segurança</h2>
<p>Adotamos medidas técnicas e organizacionais como criptografia em trânsito (HTTPS), senhas com hash, controle de acesso por permissões e regras de segurança em nível de linha no banco de dados. Nenhum sistema é 100% infalível, mas trabalhamos continuamente para reduzir riscos.</p>

<h2>7. Cookies</h2>
<p>Utilizamos cookies essenciais (sessão e autenticação) e cookies de desempenho/analytics. Você pode gerenciar cookies pelo banner exibido no primeiro acesso e pelas configurações do seu navegador. O bloqueio de cookies essenciais pode impedir o funcionamento da plataforma.</p>

<h2>8. Retenção e exclusão</h2>
<p>Mantemos seus dados enquanto sua conta estiver ativa e pelo prazo necessário para cumprir obrigações legais (como fiscais, por até 5 anos). Ao solicitar a exclusão da conta, removemos ou anonimizamos os dados que não precisamos legalmente conservar.</p>

<h2>9. Seus direitos</h2>
<p>Você pode, a qualquer momento, solicitar: confirmação de tratamento, acesso, correção, anonimização, portabilidade, eliminação, informação sobre compartilhamentos e revogação de consentimento.</p>

<h2>10. Contato do Encarregado (DPO)</h2>
<p>Solicitações podem ser enviadas para <a href="mailto:contato@outapp.com.br">contato@outapp.com.br</a>. Respondemos em até 15 dias.</p>

<h2>11. Alterações</h2>
<p>Podemos atualizar esta política. Alterações relevantes serão comunicadas na plataforma ou por e-mail.</p>
